/** One frame → the list of coloured cells. */
export function petCells(rows: string[], blink?: [number, number, string][]): { x: number, y: number, c: string }[] {
  const grid = rows.map(r => r.split(''))
  for (const [x, y, ch] of blink || []) if (grid[y]) grid[y][x] = ch
  const out: { x: number, y: number, c: string }[] = []
  grid.forEach((row, y) => row.forEach((ch, x) => { const c = PET_PALETTE[ch]; if (ch !== '.' && c) out.push({ x, y, c }) }))
  return out
}
